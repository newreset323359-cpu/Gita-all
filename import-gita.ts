const EDITION_LABEL = 'Mūla text — Sanskrit Wikisource transcription (CC BY-SA 4.0)';

export function importGita({ verbose = true } = {}) {
  const log = (...a: unknown[]) => { if (verbose) console.log(...a); };
  const chapters = JSON.parse(
    readFileSync(new URL('./data/gita.json', import.meta.url), 'utf8'),
  ) as RawChapter[];

  const work = get('SELECT id FROM works WHERE slug = ?', ['bhagavad-gita']);
  if (!work) throw new Error('bhagavad-gita work missing — run the seed first');

  let inserted = 0;
  let updated = 0;

  db.transaction(() => {
    // 0. source record (idempotent — the seed creates it too)
    run(`INSERT OR IGNORE INTO sources (slug,name,url,kind,license,copyright,notes)
         VALUES (?,?,?,?,?,?,?)`, [
      'wikisource', 'Sanskrit Wikisource (sa.wikisource.org)',
      'https://sa.wikisource.org/wiki/भगवद्गीता', 'repository',
      'CC BY-SA 4.0 — community transcription; mūla text itself is public domain',
      'Sanskrit Wikisource contributors',
      'Devanagari mūla used to index the complete Bhagavad Gītā; IAST generated by this library.',
    ]);

    // 1. edition record for the mūla transcription
    const edition = get('SELECT id FROM editions WHERE work_id = ? AND label = ?', [work.id, EDITION_LABEL]);
    if (!edition) {
      run(`INSERT INTO editions (work_id,label,language,script,translator,publisher,year,edition_type,source_slug,source_url,license,copyright,downloadable,rights_checked)
           VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?)`, [
        work.id, EDITION_LABEL, 'Sanskrit', 'Devanagari', null,
        'Sanskrit Wikisource (community transcription)', '2026', 'e-text',
        'wikisource', 'https://sa.wikisource.org/wiki/भगवद्गीता',
        'CC BY-SA 4.0 (transcription); mūla text public domain',
        'Sanskrit Wikisource contributors', 1, 1,
      ]);
    }

    // 2. chapters — create the missing adhyāyas, refresh verse counts
    const chapterId = new Map<number, number>();
    for (const ch of chapters) {
      const meta = CHAPTERS[ch.chapter];
      const row = get('SELECT id FROM chapters WHERE work_id = ? AND number = ?', [work.id, ch.chapter]);
      if (row) {
        run('UPDATE chapters SET title_sa = ?, title = ?, title_en = ?, verse_count = ? WHERE id = ?', [
          meta.sa, meta.iast, meta.en, ch.verses.length, row.id,
        ]);
        chapterId.set(ch.chapter, row.id);
      } else {
        const info = run(`INSERT INTO chapters (work_id,number,kind,title_sa,title,title_en,summary,verse_count)
             VALUES (?,?,?,?,?,?,?,?)`, [work.id, ch.chapter, 'adhyaya', meta.sa, meta.iast, meta.en, null, ch.verses.length]);
        chapterId.set(ch.chapter, Number(info.lastInsertRowid));
      }
    }

    // 3. verses — update in place where a curated verse already exists (keeps
    //    translations, word-by-word glosses, bookmarks and commentary links)
    for (const ch of chapters) {
      const cid = chapterId.get(ch.chapter)!;
      for (const v of ch.verses) {
        const existing = get(
          'SELECT id, tr_en FROM verses WHERE work_id = ? AND chapter_number = ? AND CAST(verse_number AS INTEGER) = ?',
          [work.id, ch.chapter, v.n],
        );
        const text = [v.sa, v.iast].join(' ');
        if (existing) {
          run('UPDATE verses SET chapter_id = ?, verse_number = ?, order_index = ?, sa = ?, iast = ?, fold = ? WHERE id = ?', [
            cid, String(v.n), v.n, v.sa, v.iast, fold(text), existing.id,
          ]);
          updated += 1;
        } else {
          const info = run(`INSERT INTO verses (work_id,chapter_id,chapter_number,verse_number,order_index,sa,iast,fold,tr_en,tr_hi,tr_mr,words,translation_credit,is_demo,verified,popularity)
               VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`, [
            work.id, cid, ch.chapter, String(v.n), v.n, v.sa, v.iast, fold(text),
            null, null, null, null, null, 1, 1, 20,
          ]);
          const vid = Number(info.lastInsertRowid);
          run('INSERT OR REPLACE INTO verse_vectors (verse_id,dim,vec) VALUES (?,?,?)', [vid, 256, serializeVector(embed(text))]);
          inserted += 1;
        }
      }
    }

    // 4. keep the work record honest about its extent
    const vs = get('SELECT COUNT(*) c FROM verses WHERE work_id = ?', [work.id]).c;
    run(`UPDATE works SET verse_count = ?, chapter_count = ?, updated_at = datetime('now') WHERE id = ?`, [vs, chapters.length, work.id]);
  })();

  // recompute the work's vectors (updated rows carry new text, so their vector is stale)
  const own = all(
    'SELECT id, sa, iast, tr_en FROM verses WHERE work_id = ?', [work.id],
  );
  for (const m of own) {
    const text = [m.sa, m.iast, m.tr_en].filter(Boolean).join(' ');
    run('INSERT OR REPLACE INTO verse_vectors (verse_id,dim,vec) VALUES (?,?,?)', [m.id, 256, serializeVector(embed(text))]);
  }

  // embeddings for any verse that still lacks one (updated rows keep their old vector)
  const missing = all(
    `SELECT v.id, v.sa, v.iast, v.tr_en FROM verses v
       LEFT JOIN verse_vectors vv ON vv.verse_id = v.id
      WHERE vv.verse_id IS NULL`,
  );
  for (const m of missing) {
    const text = [m.sa, m.iast, m.tr_en].filter(Boolean).join(' ');
    run('INSERT OR REPLACE INTO verse_vectors (verse_id,dim,vec) VALUES (?,?,?)', [m.id, 256, serializeVector(embed(text))]);
  }

  log(`Gītā import: ${inserted} verses inserted, ${updated} refreshed, ${missing.length} vectors recomputed`);
  log(`Total verses in work: ${get('SELECT COUNT(*) c FROM verses WHERE work_id = ?', [work.id]).c}`);
  return { inserted, updated };
}

const invokedDirectly = process.argv[1] && /import-gita\.ts$/.test(process.argv[1]);
if (invokedDirectly) importGita();
