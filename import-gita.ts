/**
 * Import the complete Bhagavad Gītā mūla (700 verses) from the Wikisource scrape.
 *
 * Source: Sanskrit Wikisource (sa.wikisource.org), CC BY-SA 4.0, verses mūla only.
 * IAST is machine-generated from the Devanagari by scripts/translit.py, so the
 * edition record is explicit about provenance and about what is *not* included
 * (no English translation is asserted for verses the library has not cleared).
 *
 * Run after `npm run seed`:  npx tsx src/seed/import-gita.ts
 */
import { readFileSync } from 'node:fs';
